def _hex_to_bgr(hex_color: str) -> tuple:
    h = hex_color.lstrip('#')
    return tuple(int(h[i:i+2], 16) for i in (4, 2, 0))

def draw_dashed_line(img, pt1, pt2, color, thickness=1, dash_length=3):
    x1, y1 = pt1
    x2, y2 = pt2
    dist = ((x2 - x1)**2 + (y2 - y1)**2)**0.5
    if dist == 0: return
    dashes = int(dist / dash_length)
    for i in range(dashes):
        if i % 2 == 0:
            start = (int(x1 + (x2 - x1) * i / dashes), int(y1 + (y2 - y1) * i / dashes))
            end = (int(x1 + (x2 - x1) * (i + 1) / dashes), int(y1 + (y2 - y1) * (i + 1) / dashes))
            cv2.line(img, start, end, color, thickness, cv2.LINE_AA)

def generate_mesh_photo_b64(img_numpy, landmarks, width: int, height: int, alpha_opacity: float = ALPHA_OPACITY) -> str:
    """Генерує фото з напівпрозорою геометричною сіткою."""
    
    overlay = img_numpy.copy()
    
    line_color = _hex_to_bgr(MESH_COLOR_HEX)
    dot_color = _hex_to_bgr(DOT_COLOR_HEX)
    
    drawn_points = set()

    for p1_idx, p2_idx in OVERALL_MESH_PAIRS:
        try:
            x1, y1 = int(landmarks[p1_idx].x * width), int(landmarks[p1_idx].y * height)
            x2, y2 = int(landmarks[p2_idx].x * width), int(landmarks[p2_idx].y * height)
            
            draw_dashed_line(overlay, (x1, y1), (x2, y2), line_color, thickness=1, dash_length=3)
            
            drawn_points.add((x1, y1))
            drawn_points.add((x2, y2))
        except (IndexError, AttributeError):
            continue
            
    for px, py in drawn_points:
        cv2.circle(overlay, (px, py), 1, dot_color, -1, cv2.LINE_AA)

    # Додаємо сітку з налаштованою прозорістю alpha_opacity
    cv2.addWeighted(overlay, alpha_opacity, img_numpy, 1 - alpha_opacity, 0, img_numpy)

    _, encoded = cv2.imencode(".jpg", img_numpy)
    b64_str = base64.b64encode(encoded.tobytes()).decode('utf-8')
    
    return f"data:image/jpeg;base64,{b64_str}"